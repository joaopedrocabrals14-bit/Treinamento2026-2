CREATE DATABASE BIBLIOTECA IF NOT EXISTS

CREATE TABLE USUARIO(
    CODUSU      INT(11) PRIMARY KEY,
    NOME        VARCHAR(255) NOT NULL,
    EMAIL       VARCHAR(100),
    CPF         VARCHAR(13) UNIQUE,
    ENDERECO    VARCHAR(255),
    TELEFONE    VARCHAR(13)
);

CREATE TABLE LIVRO(
    CODLIVRO    INT(11) PRIMARY KEY,
    TITULO      VARCHAR(255) DEFAULT 'SEM TITULO',
    DATA_PUBLI  DATE DEFAULT NULL,
);

CREATE TABLE EMPRESTIMO(
    CODEMP      INT(11) PRIMARY KEY,
    CODUSU      INT(11),
    CODLIVRO    INT(11),
    DATAEMP     DATE DEFAULT (CURRENT_DATE),
    DATAREC     DATE,
    Foreign Key (CODUSU) REFERENCES USUARIO(CODUSU),
    Foreign Key (CODLIVRO) REFERENCES LIVRO(CODLIVRO)
);



